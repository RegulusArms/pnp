#!/usr/bin/env python3
"""Independent vectors for the group signature's hash family (src/uss.c), and its parameter table.

Run by hand (CI has no Python): python3 tests/uss_vectors.py. It prints C initialisers that go into
tests/test_uss.c. Written from the definitions in docs/group.md, not from uss.c:

  h_K(M) = mac.c's polynomial: M in 8-byte little-endian blocks (the last zero-padded), acc = (acc + m_i)·K mod p
           for each block, then once more with the length in bytes; p = 2^127 - 1
  f(M)   = (parity(A0 & x) | parity(A1 & x) << 1) xor c,  x = h_K(M), A0/A1 the two 128-bit rows, c 2 bits
"""
import math

P = (1 << 127) - 1


def h(K, m):
    acc = 0
    for i in range(0, len(m), 8):
        acc = (acc + int.from_bytes(m[i:i + 8], "little")) * K % P
    acc = (acc + len(m)) * K % P
    return acc


def tag(fn, m):
    K = int.from_bytes(fn[0:16], "little")
    a0 = int.from_bytes(fn[16:32], "little")
    a1 = int.from_bytes(fn[32:48], "little")
    c = fn[48] & 3
    x = h(K, m)
    return ((bin(a0 & x).count("1") & 1) | (bin(a1 & x).count("1") & 1) << 1) ^ c


def fn_from(seed):
    b = bytearray()
    i = 0
    while len(b) < 49:
        b += (seed * 0x9E3779B97F4A7C15 + i * 0x2545F4914F6CDD1D & (2**64 - 1)).to_bytes(8, "little")
        i += 1
    b = b[:49]
    b[15] &= 0x7F
    b[48] &= 3
    return bytes(b)


msgs = [b"", b"a", b"12345678", b"123456789", bytes(range(100)), b"pnp meeting test"]
print("/* generated by tests/uss_vectors.py */")
print("static const struct { uint8_t fn[49]; int msg; int tag; } VEC[] = {")
for s in range(1, 9):
    fn = fn_from(s)
    for mi, m in enumerate(msgs):
        print("    {{%s}, %d, %d}," % (", ".join("0x%02x" % v for v in fn), mi, tag(fn, m)))
print("};")

# the parameter table (docs/group.md "Parameters"): the smallest k, in steps of 50, with every bound <= 2^-64
EPS = 0.25 + 2**-60


def s_of(l, lmax):
    return 0.49 - (l + 1) * (0.48 / (lmax + 1))


def log2_pt(k, s0):
    terms = [(math.lgamma(k + 1) - math.lgamma(v + 1) - math.lgamma(k - v + 1) + v * math.log(1 - EPS) +
              (k - v) * math.log(EPS)) / math.log(2) for v in range(math.ceil(s0 * k))]
    if not terms:
        return -math.inf
    m = max(terms)
    return m + math.log2(sum(2**(t - m) for t in terms))


def ok(N, w, lmax, k):
    dR = (w - 1) / N
    if math.log2((N - w)**2) + log2_pt(k, s_of(0, lmax)) > -64:
        return False
    hon = N * (1 - dR)
    Np = hon * (hon - 1) / 2
    for l in range(lmax + 1):
        dl = 0.5 + (l + 1) * dR
        gap = s_of(l - 1, lmax) - s_of(l, lmax)
        b = Np * (N * (dl - dR) + 1) * math.exp(-gap * gap * k / 2)
        if b > 0 and math.log2(b) > -64:
            return False
    return True


print("static const struct { int N, omega, lmax; uint32_t k; } KTAB[] = {")
for N in range(2, 9):
    for w in range(1, math.ceil((N + 1) / 2)):
        for lmax in (0, 1, 2):
            if 2 * (lmax + 1) * (w - 1) >= N:
                continue
            k = 100
            while not ok(N, w, lmax, k):
                k += 50
            print("    {%d, %d, %d, %d}," % (N, w, lmax, k))
print("};")
